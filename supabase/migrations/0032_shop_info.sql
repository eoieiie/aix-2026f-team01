-- 가게 사진. path는 shop-photos 버킷 안 경로(예: 341/1.jpg). 주소는 앱이 지금 연결된 Supabase 주소로 만든다
create table if not exists public.shop_photos (
  id bigint generated always as identity primary key,
  restaurant_id bigint not null references public.restaurants (id) on delete cascade,
  path text not null check (path ~ '^[a-z0-9][a-z0-9/_-]*\.(jpg|jpeg|png|webp)$'),
  -- 작은 수가 먼저. 0번이 목록과 상세 맨 위에 보이는 대표 사진
  sort int not null default 0,
  -- 누가 준 사진인지: '사장님 제공', '밥BTI 팀 촬영'
  credit text check (credit is null or char_length(credit) <= 40),
  created_at timestamptz not null default now(),
  unique (restaurant_id, path)
);
