-- 사진 버킷. 공개 읽기, 파일 하나 5MB, 그림 파일만. storage.objects에 쓰기 정책을 만들지 않아서
-- 앱 사용자는 올리거나 지울 수 없고, 팀이 대시보드로만 올린다(0016의 restaurant-photos와 같은 방식)
do $$
begin
  if exists (
    select 1 from information_schema.columns
    where table_schema = 'storage' and table_name = 'buckets' and column_name = 'allowed_mime_types'
  ) then
    execute $q$
      insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
      values ('shop-photos', 'shop-photos', true, 5242880, array['image/jpeg', 'image/png', 'image/webp'])
      on conflict (id) do update set
        public = excluded.public,
        file_size_limit = excluded.file_size_limit,
        allowed_mime_types = excluded.allowed_mime_types
    $q$;
  else
    raise notice 'storage.buckets에 public 칸이 없어 shop-photos 버킷을 만들지 않았다';
  end if;
end;
$$;

-- 사진이 없는 가게에 쓸 음식 그림: 대표 메뉴 → 가게 이름에 든 음식 → 종류의 대표 음식.
-- 그림(image_path)이 있는 기본 음식만. 카페와 종류를 모르는 가게는 null이고 화면이 아이콘을 그린다
create or replace function public.shop_thumb_food(p_name text, p_menus text[], p_cuisine text)
returns bigint
language sql stable set search_path = ''
as $$
  select coalesce(
    (select f.id from public.foods f
     join unnest(p_menus) with ordinality as m (name, ord) on m.name = f.name
     where f.image_path is not null and not f.custom
     order by m.ord limit 1),
    (select f.id from public.foods f
     where f.image_path is not null and not f.custom and strpos(p_name, f.name) > 0
     order by char_length(f.name) desc, f.id limit 1),
    (select f.id from public.foods f
     where f.image_path is not null and not f.custom
       and f.name = case p_cuisine
         when 'korean' then '비빔밥'
         when 'chinese' then '짜장면'
         when 'japanese' then '초밥'
         when 'western' then '피자'
         when 'asian' then '쌀국수'
       end
     order by f.id limit 1)
  )
$$;

-- 가게 목록. 동네는 내가 가장 최근에 들어간 모임의 동네, 모임이 없으면 erica.
-- 순서: 제휴 먼저 → 정문에서 가까운 순 → 이름. 쿠폰 문구는 제휴 가게만 나간다
create or replace function public.shop_list()
returns table (
  id bigint, name text, cuisine text, partner boolean, coupon_text text,
  walk_minutes int, open_now boolean, photo_path text, thumb_food_id bigint, thumb_image text,
  lat double precision, lng double precision, menus text[]
)
language plpgsql stable security definer set search_path = ''
as $$
declare
  v_uid uuid := public.require_uid();
  v_area text;
begin
  select g.area into v_area
  from public.memberships m
  join public.groups g on g.id = m.group_id
  where m.user_id = v_uid
  order by m.joined_at desc
  limit 1;
  v_area := coalesce(v_area, 'erica');

  return query
  select r.id, r.name, r.cuisine, r.partner,
    case when r.partner then r.coupon_text end,
    w.minutes,
    public.is_open_now(r.opening_hours),
    (select p.path from public.shop_photos p where p.restaurant_id = r.id order by p.sort, p.id limit 1),
    t.food_id,
    (select f.image_path from public.foods f where f.id = t.food_id),
    r.lat, r.lng, r.menus
  from public.restaurants r
  cross join lateral (select public.shop_thumb_food(r.name, r.menus, r.cuisine) as food_id) t
  cross join lateral (select public.walk_minutes(r.area, r.lat, r.lng) as minutes) w
  where r.area = v_area
  order by r.partner desc, w.minutes nulls last, r.name, r.id;
end;
$$;

-- 가게 상세. 가게 정보는 공개된 것이라 로그인한 사람 누구나 본다.
-- visits: 직원 확인까지 끝난 쿠폰으로 다녀간 팀 수(판에서 받은 쿠폰은 판 하나가 한 팀). 5팀이 안 되면 null이라 화면에 안 보인다
create or replace function public.shop_detail(p_restaurant_id bigint) returns jsonb
language plpgsql stable security definer set search_path = ''
as $$
declare
  r public.restaurants;
  v_food bigint;
  v_visits int;
begin
  perform public.require_uid();
  select * into r from public.restaurants x where x.id = p_restaurant_id;
  if not found then
    raise exception 'not_found';
  end if;
  v_food := public.shop_thumb_food(r.name, r.menus, r.cuisine);
  select count(distinct coalesce(c.session_id::text, c.id::text))::int into v_visits
  from public.coupon_claims c
  where c.restaurant_id = r.id and c.redeemed_at is not null;

  return jsonb_build_object(
    'id', r.id,
    'name', r.name,
    'cuisine', r.cuisine,
    'partner', r.partner,
    'coupon_text', case when r.partner then r.coupon_text end,
    'address', r.address,
    'phone', r.phone,
    'opening_hours', r.opening_hours,
    'licensed_year', extract(year from r.licensed_on)::int,
    'menus', to_jsonb(r.menus),
    'walk_minutes', public.walk_minutes(r.area, r.lat, r.lng),
    'open_now', public.is_open_now(r.opening_hours),
    'lat', r.lat,
    'lng', r.lng,
    'photos', coalesce(
      (select jsonb_agg(jsonb_build_object('path', p.path, 'credit', p.credit) order by p.sort, p.id)
       from public.shop_photos p where p.restaurant_id = r.id),
      '[]'::jsonb),
    'thumb_food_id', v_food,
    'thumb_image', (select f.image_path from public.foods f where f.id = v_food),
    'visits', case when v_visits >= 5 then v_visits end
  );
end;
$$;

revoke execute on function public.shop_thumb_food(text, text[], text), public.shop_list(), public.shop_detail(bigint)
  from public, anon;
grant execute on function public.shop_list(), public.shop_detail(bigint) to authenticated;
