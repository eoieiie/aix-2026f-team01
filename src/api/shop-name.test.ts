import { shortShopName } from './shop-name';

describe('shortShopName (2026-11-25)', () => {
  it.each([
    ['이삭토스트 안산한양대점', '이삭토스트'],
    ['모모커피 안산한양대점', '모모커피'],
    ['대홍훠궈샤브샤브(한양대점)', '대홍훠궈샤브샤브'],
    ['보배반점 안산한양대에리카점', '보배반점'],
    ['팔도반점 안산직영점', '팔도반점'],
    ['탕화쿵푸마라탕 한양대에리카점', '탕화쿵푸마라탕'],
    ['도야짬뽕안산한양대점', '도야짬뽕'],
    ['신전떡볶이한양대점', '신전떡볶이'],
    ['봉구스밥버거(안산한양대점)', '봉구스밥버거'],
    ['인더비엣(안산한양대에리카점)', '인더비엣'],
    ['바우네나주곰탕(사동점)', '바우네나주곰탕'],
    ['한양솥밥 사동본점', '한양솥밥'],
    ['교반안산상록수점', '교반'],
    ['오늘도부찌안산한대점', '오늘도부찌'],
    ['원조감자탕 일미집 안산한양대점', '원조감자탕 일미집'],
  ])('%s → %s', (name, short) => {
    expect(shortShopName(name)).toBe(short);
  });

  it.each([['보배반점'], ['홍콩반점'], ['북경중화요리'], ['코지홀리데이'], ['한양 분식 (예시)'], ['본점']])(
    '이름 자체인 것은 그대로: %s',
    (name) => {
      expect(shortShopName(name)).toBe(name);
    }
  );
});
